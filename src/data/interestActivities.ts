// Helper to retrieve themed activities strictly matching selected interests
export function getActivitiesForInterests(
  selectedInterests: string[],
  fallbackInterest: string = 'nature'
): ThemedActivity[] {
  const result: ThemedActivity[] = [];
  
  // If specific interests are selected, gather activities ONLY from those interests
  selectedInterests.forEach(interest => {
    const list = INTEREST_ACTIVITIES[interest.toLowerCase()];
    if (list && list.length > 0) {
      result.push(...list);
    }
  });

  if (result.length === 0) {
    const defaultList = INTEREST_ACTIVITIES[fallbackInterest] || INTEREST_ACTIVITIES['nature'];
    result.push(...defaultList);
  }

  return result;
}
